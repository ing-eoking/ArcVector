//! ArcVector — vector search as an arcus ASCII protocol extension.
//!
//! ```text
//! lib.rs      extension registration and the memcached callbacks
//!   protocol  argument access, replies, the nread body transfer
//!   command   one handler per command
//!   registry  live indexes and the lazy rebuild
//!   store     arcus Map engine access          (all raw pointers live here)
//!   index     usearch wrapper and concurrency
//!   codec     element byte layout              (pure)
//!   quant     f32 -> f16/i8/b1                 (pure)
//!   filter    filter expressions               (pure)
//! ```
//!
//! The single consistency rule: **the usearch index is a cache rebuildable from
//! Map. If it is not in Map, it does not exist.** Restart, eviction, TTL expiry
//! and replication slaves are all covered by it.

