/// Engine access for the callback currently running.
///
/// # Safety
///
/// `cookie` must be the cookie memcached passed to that callback.
unsafe fn store_for(cookie: *const c_void) -> Result<Store> {
    // SAFETY: guaranteed by the caller.
    unsafe { Store::for_cookie(cookie) }.ok_or(Error::Store(StoreError::Unavailable))
}

/// Route one command line, or resume one whose body has arrived.
///
/// # Safety
///
/// `tokens` must borrow the argument vector memcached passed to `execute`, and
/// `cookie` must be that call's connection cookie.
unsafe fn dispatch(cookie: *const c_void, tokens: &Tokens) -> Result<Reply> {
    // SAFETY: guaranteed by the caller.
    let store = unsafe { store_for(cookie) };

    // An empty argument vector means the body of a two-phase command arrived.
    if tokens.is_empty() {
        let pending =
            protocol::take_body(cookie).ok_or_else(|| Error::bad_request("lost command state"))?;
        let store = store?;
        let (cmd, body) = pending.into_parts();
        return match cmd {
            PendingCmd::Add { index, id, attr } => {
                command::vadd(&store, &index, &id, &attr?, &body)
            }
            PendingCmd::Search {
                index,
                k,
                vec_bytes,
            } => command::vsearch(&store, &index, k, vec_bytes, &body),
        };
    }

    match tokens.command() {
        "vcreate" => command::vcreate(&store?, tokens),
        "vget" => command::vget(&store?, tokens),
        "vdel" => command::vdel(&store?, tokens),
        "vdrop" => command::vdrop(&store?, tokens),
        "vlist" => command::vlist(tokens),
        // A well-formed vadd/vsearch completes through the body phase above, so
        // reaching here means the command line itself was malformed.
        "vadd" | "vsearch" => Err(Error::bad_request("bad command line format")),
        other => Err(Error::bad_request(format!("unknown command {other}"))),
    }
}

/// Length of a body segment, rejecting values that cannot be transferred.
fn blob_len(tokens: &Tokens, at: usize, what: &str, float_aligned: bool) -> Option<usize> {
    let n: usize = tokens.parse(at, what).ok()?;
    if n > MAX_BLOB_BYTES {
        return None;
    }
    if float_aligned && (n == 0 || !n.is_multiple_of(4)) {
        return None;
    }
    Some(n)
}

/// Read `ATTR <attrlen> <attr JSON>` off a `vadd` line.
///
/// The clause is optional; without it a vector is stored with no attributes.
/// `accept` cannot answer the client, so a malformed clause is returned as an
/// error for `command::vadd` to report.
fn read_attr(tokens: &Tokens) -> std::result::Result<Vec<u8>, Error> {
    if tokens.len() == 4 {
        return Ok(Vec::new());
    }
    let keyword = tokens.text(4)?;
    if !keyword.eq_ignore_ascii_case("ATTR") {
        return Err(Error::bad_request(format!(
            "expected ATTR after the vector length, got '{keyword}'"
        )));
    }
    let declared: usize = tokens.parse(5, "ATTR length")?;
    if declared > codec::ATTR_BYTES {
        return Err(Error::bad_request(format!(
            "ATTR is {declared} bytes, over the {}-byte limit",
            codec::ATTR_BYTES
        )));
    }
    if declared == 0 {
        return Ok(Vec::new());
    }

    let attr = tokens.tail(6, codec::ATTR_BYTES)?;
    if attr.len() != declared {
        return Err(Error::bad_request(format!(
            "ATTR length {declared} does not match the {} bytes supplied",
            attr.len()
        )));
    }
    Ok(attr)
}

/// Decide how much body a command needs before it can run.
///
/// Returning `true` without setting `ndata` makes memcached call `execute` on
/// the command line, where the malformed input is reported.
///
/// # Safety
///
/// `argv`, `ndata` and `ptr_out` must be the parameters memcached passed to the
/// `accept` callback.
unsafe extern "C" fn accept_vector_cmd(
    _cmd_cookie: *const c_void,
    cookie: *mut c_void,
    argc: c_int,
    argv: *mut token_t,
    ndata: *mut usize,
    ptr_out: *mut *mut c_char,
) -> bool {
    // SAFETY: guaranteed by the caller.
    let tokens = unsafe { Tokens::new(argv, argc) };

    // vadd    <index> <id> <veclen> [ATTR <attrlen> <attr JSON>]  then <vector>\r\n
    // vsearch <index> <k>  <veclen> [filterlen]                   then <vector><filter>\r\n
    //
    // ATTR rides on the command line because it is short and bounded. The search
    // filter does not: an expression with spaces would be at the mercy of the
    // tokenizer's field limit, so it travels in the body instead.
    let cmd = tokens.command();
    match cmd {
        "vcreate" | "vget" | "vdel" | "vdrop" | "vlist" => return true,
        "vadd" | "vsearch" => {}
        _ => return false,
    }
    if tokens.len() < 4 {
        return true;
    }
    let Some(vec_bytes) = blob_len(&tokens, 3, "vector length", true) else {
        return true;
    };
    let Ok(index) = tokens.text(1).map(str::to_owned) else {
        return true;
    };

    let (pending, body_len) = if cmd == "vadd" {
        let Ok(id) = tokens.text(2).map(str::to_owned) else {
            return true;
        };
        // The body is exactly the vector; ATTR was already on the line.
        (
            PendingCmd::Add {
                index,
                id,
                attr: read_attr(&tokens),
            },
            vec_bytes,
        )
    } else {
        if tokens.len() > 5 {
            return true;
        }
        let Ok(k) = tokens.parse::<usize>(2, "k") else {
            return true;
        };
        if k == 0 {
            return true;
        }
        let filter_bytes = if tokens.len() == 5 {
            match blob_len(&tokens, 4, "filter length", false) {
                Some(n) => n,
                None => return true,
            }
        } else {
            0
        };
        (
            PendingCmd::Search {
                index,
                k,
                vec_bytes,
            },
            vec_bytes + filter_bytes,
        )
    };

    // SAFETY: guaranteed by the caller.
    unsafe { protocol::expect_body(cookie, pending, body_len, ndata, ptr_out) };
    true
}

/// # Safety
///
/// `argv` and `handler` must be the parameters memcached passed to `execute`.
unsafe extern "C" fn execute_vector_cmd(
    _cmd_cookie: *const c_void,
    cookie: *const c_void,
    argc: c_int,
    argv: *mut token_t,
    handler: ResponseHandler,
) -> bool {
    // SAFETY: guaranteed by the caller.
    let tokens = unsafe { Tokens::new(argv, argc) };
    // SAFETY: `cookie` belongs to the call in progress.
    let outcome = unsafe { dispatch(cookie, &tokens) };
    Responder::new(handler, cookie).reply(outcome);
    true
}

/// Release a body whose command never completed.
unsafe extern "C" fn abort_vector_cmd(_cmd_cookie: *const c_void, cookie: *const c_void) {
    drop(protocol::take_body(cookie));
}

unsafe extern "C" fn get_name_vector(_cmd_cookie: *const c_void) -> *const c_char {
    c"arcus-vector-db".as_ptr()
}

static mut VECTOR_DESCRIPTOR: EXTENSION_ASCII_PROTOCOL_DESCRIPTOR =
    EXTENSION_ASCII_PROTOCOL_DESCRIPTOR {
        get_name: Some(get_name_vector),
        get_auth_flag: None,
        accept: Some(accept_vector_cmd),
        execute: Some(execute_vector_cmd),
        abort: Some(abort_vector_cmd),
        cookie: ptr::null_mut(),
        next: ptr::null_mut(),
    };

/// Entry point memcached calls when loading the extension.
#[unsafe(no_mangle)]
pub extern "C" fn memcached_extensions_initialize(
    _config: *const c_char,
    get_server_api: GET_SERVER_API,
) -> EXTENSION_ERROR_CODE {
    let Some(get_api) = get_server_api else {
        return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
    };
    store::set_server_api(get_api);

    // SAFETY: memcached hands us a live SERVER_HANDLE_V1 accessor, and the
    // descriptor is a process-lifetime static that the server only reads.
    unsafe {
        let server = get_api();
        if server.is_null() {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        }
        let extension = (*server).extension;
        if extension.is_null() {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        }
        let Some(register) = (*extension).register_extension else {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        };
        if !register(
            extension_type_t_EXTENSION_ASCII_PROTOCOL,
            (&raw mut VECTOR_DESCRIPTOR).cast::<c_void>(),
        ) {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        }
    }
    EXTENSION_ERROR_CODE_EXTENSION_SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;

    use protocol::tokenize_for_test as tokenize;

    fn attr_of(line: &str) -> Result<Vec<u8>> {
        let (_buf, raw) = tokenize(line);
        // SAFETY: `raw` and its buffer outlive the borrow.
        let tokens = unsafe { Tokens::new(raw.as_ptr(), raw.len() as c_int) };
        read_attr(&tokens)
    }

    #[test]
    fn attr_is_optional() {
        assert_eq!(attr_of("vadd docs v1 16").unwrap(), Vec::<u8>::new());
    }

    #[test]
    fn attr_is_read_off_the_command_line() {
        let json = r#"{"cat":"tech"}"#;
        assert_eq!(
            attr_of(&format!("vadd docs v1 16 ATTR {} {json}", json.len())).unwrap(),
            json.as_bytes()
        );
    }

    #[test]
    fn attr_with_spaces_is_reassembled() {
        let json = r#"{"cat": "tech", "ts": 1723248000}"#;
        assert_eq!(
            attr_of(&format!("vadd docs v1 16 ATTR {} {json}", json.len())).unwrap(),
            json.as_bytes()
        );
    }

    #[test]
    fn the_attr_keyword_is_case_insensitive() {
        assert!(attr_of("vadd docs v1 16 attr 2 {}").is_ok());
        assert!(attr_of("vadd docs v1 16 Attr 2 {}").is_ok());
    }

    #[test]
    fn a_missing_or_misspelled_keyword_is_reported() {
        let msg = attr_of("vadd docs v1 16 ATTRS 2 {}")
            .unwrap_err()
            .to_string();
        assert!(msg.contains("expected ATTR"), "{msg}");
    }

    #[test]
    fn a_declared_length_over_the_limit_is_rejected_before_reading() {
        // "미리 넘거나 하면 에러": the declared size alone is enough to refuse.
        let msg = attr_of("vadd docs v1 16 ATTR 129 {}")
            .unwrap_err()
            .to_string();
        assert!(msg.contains("over the 128-byte limit"), "{msg}");

        // Exactly at the limit is accepted. Built from real content, since
        // leading spaces are separators to the tokenizer, not part of the value.
        let json = format!(r#"{{"k":"{}"}}"#, "x".repeat(120));
        assert_eq!(json.len(), codec::ATTR_BYTES);
        assert!(attr_of(&format!("vadd docs v1 16 ATTR 128 {json}")).is_ok());
    }

    #[test]
    fn a_declared_length_that_disagrees_with_the_payload_is_rejected() {
        let msg = attr_of("vadd docs v1 16 ATTR 99 {}")
            .unwrap_err()
            .to_string();
        assert!(msg.contains("does not match"), "{msg}");
    }

    #[test]
    fn a_zero_length_attr_is_treated_as_absent() {
        assert_eq!(attr_of("vadd docs v1 16 ATTR 0").unwrap(), Vec::<u8>::new());
    }

    #[test]
    fn a_non_numeric_length_is_reported() {
        let msg = attr_of("vadd docs v1 16 ATTR abc {}")
            .unwrap_err()
            .to_string();
        assert!(msg.contains("ATTR length"), "{msg}");
    }
}
