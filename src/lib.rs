/// Engine access for the callback currently running.
///
/// # Safety
///
/// `cookie` must be the cookie memcached passed to that callback.
unsafe fn store_for(cookie: *const c_void) -> Result<Store> {
    // SAFETY: guaranteed by the caller.
    unsafe { Store::for_cookie(cookie) }.ok_or(Error::Store(StoreError::Unavailable))
}

/// Route one command line, or resume one whose body has arrived.
///
/// # Safety
///
/// `tokens` must borrow the argument vector memcached passed to `execute`, and
/// `cookie` must be that call's connection cookie.
unsafe fn dispatch(cookie: *const c_void, tokens: &Tokens) -> Result<Reply> {
    // SAFETY: guaranteed by the caller.
    let store = unsafe { store_for(cookie) };

    // An empty argument vector means the body of a two-phase command arrived.
    if tokens.is_empty() {
        let pending =
            protocol::take_body(cookie).ok_or_else(|| Error::bad_request("lost command state"))?;
        let store = store?;
        return match &pending.cmd {
            PendingCmd::Add {
                index,
                id,
                vec_bytes,
            } => command::vadd(&store, index, id, *vec_bytes, pending.body()),
            PendingCmd::Search {
                index,
                k,
                vec_bytes,
            } => command::vsearch(&store, index, *k, *vec_bytes, pending.body()),
        };
    }

    match tokens.command() {
        "vcreate" => command::vcreate(&store?, tokens),
        "vget" => command::vget(&store?, tokens),
        "vdel" => command::vdel(&store?, tokens),
        "vdrop" => command::vdrop(&store?, tokens),
        "vlist" => command::vlist(tokens),
        // A well-formed vadd/vsearch completes through the body phase above, so
        // reaching here means the command line itself was malformed.
        "vadd" | "vsearch" => Err(Error::bad_request("bad command line format")),
        other => Err(Error::bad_request(format!("unknown command {other}"))),
    }
}

/// Length of a body segment, rejecting values that cannot be transferred.
fn blob_len(tokens: &Tokens, at: usize, what: &str, float_aligned: bool) -> Option<usize> {
    let n: usize = tokens.parse(at, what).ok()?;
    if n > MAX_BLOB_BYTES {
        return None;
    }
    if float_aligned && (n == 0 || !n.is_multiple_of(4)) {
        return None;
    }
    Some(n)
}

/// Decide how much body a command needs before it can run.
///
/// Returning `true` without setting `ndata` makes memcached call `execute` on
/// the command line, where the malformed input is reported.
///
/// # Safety
///
/// `argv`, `ndata` and `ptr_out` must be the parameters memcached passed to the
/// `accept` callback.
unsafe extern "C" fn accept_vector_cmd(
    _cmd_cookie: *const c_void,
    cookie: *mut c_void,
    argc: c_int,
    argv: *mut token_t,
    ndata: *mut usize,
    ptr_out: *mut *mut c_char,
) -> bool {
    // SAFETY: guaranteed by the caller.
    let tokens = unsafe { Tokens::new(argv, argc) };

    // vadd    <index> <id> <veclen> [jsonlen]    then <vector><json>\r\n
    // vsearch <index> <k>  <veclen> [filterlen]  then <vector><filter>\r\n
    //
    // The tail travels in the body rather than as command-line tokens so that a
    // filter expression containing spaces is not subject to the tokenizer's
    // field limit.
    let (cmd, vec_bytes, tail) = match tokens.command() {
        "vcreate" | "vget" | "vdel" | "vdrop" | "vlist" => return true,
        cmd @ ("vadd" | "vsearch") => {
            if !matches!(tokens.len(), 4 | 5) {
                return true;
            }
            let Some(vec_bytes) = blob_len(&tokens, 3, "vector length", true) else {
                return true;
            };
            let tail = if tokens.len() == 5 {
                match blob_len(&tokens, 4, "payload length", false) {
                    Some(n) => n,
                    None => return true,
                }
            } else {
                0
            };
            (cmd, vec_bytes, tail)
        }
        _ => return false,
    };

    let Ok(index) = tokens.text(1).map(str::to_owned) else {
        return true;
    };
    let pending = if cmd == "vadd" {
        let Ok(id) = tokens.text(2).map(str::to_owned) else {
            return true;
        };
        PendingCmd::Add {
            index,
            id,
            vec_bytes,
        }
    } else {
        let Ok(k) = tokens.parse::<usize>(2, "k") else {
            return true;
        };
        if k == 0 {
            return true;
        }
        PendingCmd::Search {
            index,
            k,
            vec_bytes,
        }
    };

    // SAFETY: guaranteed by the caller.
    unsafe { protocol::expect_body(cookie, pending, vec_bytes + tail, ndata, ptr_out) };
    true
}

/// # Safety
///
/// `argv` and `handler` must be the parameters memcached passed to `execute`.
unsafe extern "C" fn execute_vector_cmd(
    _cmd_cookie: *const c_void,
    cookie: *const c_void,
    argc: c_int,
    argv: *mut token_t,
    handler: ResponseHandler,
) -> bool {
    // SAFETY: guaranteed by the caller.
    let tokens = unsafe { Tokens::new(argv, argc) };
    // SAFETY: `cookie` belongs to the call in progress.
    let outcome = unsafe { dispatch(cookie, &tokens) };
    Responder::new(handler, cookie).reply(outcome);
    true
}

/// Release a body whose command never completed.
unsafe extern "C" fn abort_vector_cmd(_cmd_cookie: *const c_void, cookie: *const c_void) {
    drop(protocol::take_body(cookie));
}

unsafe extern "C" fn get_name_vector(_cmd_cookie: *const c_void) -> *const c_char {
    c"arcus-vector-db".as_ptr()
}

static mut VECTOR_DESCRIPTOR: EXTENSION_ASCII_PROTOCOL_DESCRIPTOR =
    EXTENSION_ASCII_PROTOCOL_DESCRIPTOR {
        get_name: Some(get_name_vector),
        get_auth_flag: None,
        accept: Some(accept_vector_cmd),
        execute: Some(execute_vector_cmd),
        abort: Some(abort_vector_cmd),
        cookie: ptr::null_mut(),
        next: ptr::null_mut(),
    };

/// Entry point memcached calls when loading the extension.
#[unsafe(no_mangle)]
pub extern "C" fn memcached_extensions_initialize(
    _config: *const c_char,
    get_server_api: GET_SERVER_API,
) -> EXTENSION_ERROR_CODE {
    let Some(get_api) = get_server_api else {
        return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
    };
    store::set_server_api(get_api);

    // SAFETY: memcached hands us a live SERVER_HANDLE_V1 accessor, and the
    // descriptor is a process-lifetime static that the server only reads.
    unsafe {
        let server = get_api();
        if server.is_null() {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        }
        let extension = (*server).extension;
        if extension.is_null() {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        }
        let Some(register) = (*extension).register_extension else {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        };
        if !register(
            extension_type_t_EXTENSION_ASCII_PROTOCOL,
            (&raw mut VECTOR_DESCRIPTOR).cast::<c_void>(),
        ) {
            return EXTENSION_ERROR_CODE_EXTENSION_FATAL;
        }
    }
    EXTENSION_ERROR_CODE_EXTENSION_SUCCESS
}
